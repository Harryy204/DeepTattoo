let currentLang = localStorage.getItem("aether_lang") || "en";


function setLanguage(lang) {
  if (!translations[lang]) return;
  currentLang = lang;
  localStorage.setItem("aether_lang", lang);

  // Update all elements with data-i18n
  document.querySelectorAll("[data-i18n]").forEach((el) => {
    const key = el.getAttribute("data-i18n");
    if (translations[lang][key]) {
      el.textContent = translations[lang][key];
    }
  });

  // Update placeholders if any
  document.querySelectorAll("[data-i18n-placeholder]").forEach((el) => {
    const key = el.getAttribute("data-i18n-placeholder");
    if (translations[lang][key]) {
      el.placeholder = translations[lang][key];
    }
  });

  // Update aria-labels
  document.querySelectorAll("[data-i18n-aria]").forEach((el) => {
    const key = el.getAttribute("data-i18n-aria");
    if (translations[lang][key]) {
      el.setAttribute("aria-label", translations[lang][key]);
    }
  });

  // Update document title and meta
  if (translations[lang].meta_title) {
    document.title = translations[lang].meta_title;
  }
  const metaDesc = document.querySelector('meta[name="description"]');
  if (metaDesc && translations[lang].meta_description) {
    metaDesc.setAttribute("content", translations[lang].meta_description);
  }

  // Update language switcher UI
  document.querySelectorAll(".lang-btn").forEach((btn) => {
    btn.classList.toggle("active", btn.dataset.lang === lang);
  });

  // Update html lang attribute
  document.documentElement.lang = lang;

  // Dispatch event for dynamic content updates
  document.dispatchEvent(new CustomEvent("languageChanged", { detail: { lang } }));
}

function t(key) {
  return translations[currentLang][key] || key;
}

function initLanguage() {
  setLanguage(currentLang);

  document.querySelectorAll(".lang-btn").forEach((btn) => {
    btn.addEventListener("click", () => {
      setLanguage(btn.dataset.lang);
    });
  });
}

// Export for other modules
window.AETHER = window.AETHER || {};
window.AETHER.t = t;
window.AETHER.setLanguage = setLanguage;
window.AETHER.currentLang = () => currentLang;
window.AETHER.translations = translations;
